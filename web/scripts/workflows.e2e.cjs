/* Requires the disposable official-reference E2E server after csv-upload.e2e.cjs. */
const {chromium} = require(process.env.CC_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const origin = process.env.CC_E2E_URL;
assert.ok(origin && ['localhost','127.0.0.1'].includes(new URL(origin).hostname));
assert.equal(process.env.CC_E2E_CONFIRM_DISPOSABLE, '1', 'Explicit disposable-server acknowledgement required');
assert.ok(process.env.CC_E2E_PASSWORD);
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true,chromiumSandbox:true});
 const output=await fs.mkdtemp(path.join(os.tmpdir(),'sevaro-workflows-e2e-'));
 const failures=[], checks=[], pageErrors=[];
 let step='sign-in', coord;
 const check=(name,okay,detail)=>{checks.push({name,pass:Boolean(okay)});if(!okay)failures.push({name,detail});};
 const login=async(email,role)=>{
  const context=await browser.newContext({viewport:{width:1440,height:1100}});
  const page=await context.newPage();page.setDefaultTimeout(15000);
  page.on('pageerror',e=>pageErrors.push(e.message));
  await page.goto(origin+'/#signin');
  check(role+' sign-in email has an accessible label',await page.getByLabel('Work email',{exact:true}).count()===1);
  check(role+' sign-in password has an accessible label',await page.getByLabel('Password',{exact:true}).count()===1);
  await page.getByPlaceholder('name@sevaro.com').fill(email);
  await page.locator('input[type=password]').fill(process.env.CC_E2E_PASSWORD);
  if(role==='physician')await page.getByRole('button',{name:'Physician Your shifts & consults'}).click();
  await page.getByRole('button',{name:role==='physician'?'Sign in as Physician':'Sign in as Coordinator'}).click();
  await page.getByRole('link',{name:role==='physician'?'My shift':role==='lead'?'Approvals':'Command',exact:true}).waitFor();
  const session=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('cc_session')));
  assert.equal(session.user.role,role);
  const headers={Authorization:'Bearer '+session.token};
  const request=async(route,payload,expected=200)=>{
   const r=await (payload===undefined?page.request.get(origin+route,{headers}):page.request.post(origin+route,{headers,data:payload}));
   assert.equal(r.status(),expected,route+': '+await r.text());
   return r.json();
  };
  return {page,request,headers};
 };
 try{
  coord=await login(process.env.CC_E2E_COORDINATOR_EMAIL||'coord@e2e.local','coordinator');
  const lead=await login(process.env.CC_E2E_LEAD_EMAIL||'lead@e2e.local','lead');
  const physician=await login(process.env.CC_E2E_PHYSICIAN_EMAIL||'physician@e2e.local','physician');
  const other=await login(process.env.CC_E2E_OTHER_EMAIL||'other@e2e.local','physician');
  const initial=await coord.request('/snapshot');
  const refs=await coord.request('/admin/references');
  assert.equal(refs.manifest.fingerprint,'81602969911fe81fc1d5db5a51595fb5124d07ac5f5e97623a21e1232701d72d');
  assert.equal(initial.clock.now,'2026-03-17T22:30:00+00:00');
  assert.equal((await coord.request('/offers')).items.length,0,'Fresh workflow fixture required');
  step='lead permissions';
  check('Lead workspace hides coordinator Command',await lead.page.getByRole('link',{name:'Command',exact:true}).count()===0);
  check('Lead command hides coordinator-only mutations',await lead.page.locator('.dossier-actions button').count()===0,'Lead sees Reassign/Escalate buttons despite lacking ops.intervene');
  await lead.request('/interventions',{kind:'escalate',item_id:initial.queue.items[0].id},403);
  step='coordinator navigation';
  for(const [name,heading] of [['Consults','Consults'],['Doctors','Doctors'],['Schedule','Shift schedule'],['Audit','Audit'],['Data','Data']]){
   await coord.page.getByRole('link',{name,exact:true}).click();
   await coord.page.getByRole('heading',{name:heading,exact:true}).waitFor();
   check(name+' desktop has no page overflow',await coord.page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   await coord.page.setViewportSize({width:390,height:844});
   check(name+' mobile has no page overflow',await coord.page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   await coord.page.setViewportSize({width:1440,height:1100});
  }
  step='proposal';
  await coord.page.getByRole('link',{name:'Command',exact:true}).click();
  await coord.page.locator('.dense-queue-row').filter({hasText:'Suncrest Medical Pavilion: 0 of 2'}).click();
  await coord.page.locator('.dossier-actions').getByRole('button',{name:'Find cover',exact:true}).click();
  await coord.page.getByRole('heading',{name:'Off-shift physicians',exact:true}).waitFor();
  await coord.page.locator('.candidates tr').filter({hasText:'Dr. Grace Okafor'}).getByRole('button',{name:'Propose offer'}).click();
  await coord.page.getByRole('button',{name:'Send to clinical lead',exact:true}).click();
  await coord.page.getByRole('heading',{name:'Off-shift physicians',exact:true}).waitFor({state:'hidden'});
  let offer=(await coord.request('/offers')).items[0];assert.equal(offer.state,'Proposed');
  check('Proposal invisible to physician',(await physician.request('/me/offers')).items.length===0);
  await coord.request('/offers/'+offer.offer_id+'/approve',{},403);
  step='lead approval';
  await lead.page.getByRole('link',{name:/^Approvals/}).click();
  await lead.page.getByRole('button',{name:'Approve and send',exact:true}).click();
  assert.equal((await coord.request('/offers')).items[0].state,'Sent');
  await other.request('/offers/'+offer.offer_id+'/accept',{},404);
  step='physician acceptance';
  await physician.page.getByRole('link',{name:'Offers',exact:true}).click();
  await physician.page.getByRole('button',{name:'Accept',exact:true}).click();
  await physician.page.getByText('Accepted',{exact:true}).waitFor();
  check('Offer accepted',(await coord.request('/offers')).items[0].state==='Accepted');
  await coord.request('/admin/clock',{at:'2026-03-17T18:32:00-04:00',paused:true});
  const own = await physician.request('/me/shift');
  assert.equal(own.on_shift,false);
  const loadedShift=physician.page.waitForResponse(r=>r.url().includes('/me/shift')&&r.status()===200);
  await physician.page.getByRole('link',{name:'My shift',exact:true}).click();
  await loadedShift;
  await physician.page.getByText(/until .* ET/).waitFor();
  check('Accepted physician is not shown online before arrival',await physician.page.getByText('Awaiting arrival',{exact:true}).count()===1);
  const waiting=(await coord.request('/schedule')).doctors.find(d=>d.id==='PHY-009');
  check('Acceptance awaits observed arrival',waiting.status==='Accepted; awaiting observed arrival');
  step='arrival';
  await coord.request('/admin/clock',{at:'2026-03-17T18:46:00-04:00',paused:true});
  const arrivals=await coord.request('/events',{event_id:'E2E-ARRIVAL',event_type:'shift_started',physician_id:'PHY-009',event_time:'2026-03-17T18:46:00-04:00',ingested_at:'2026-03-17T18:46:00-04:00'});
  assert.equal(arrivals.accepted,1);
  const arrived=await coord.request('/snapshot');
  const joiner=arrived.physicians.items.find(p=>p.physician_id==='PHY-009');
  check('Observed arrival enables routing',joiner.routable);
  const scheduled=(await coord.request('/schedule')).doctors.find(d=>d.id==='PHY-009');
  check('Schedule confirms arrival',scheduled.group==='On shift');
  check('Joiner remains limited to offered hospitals',joiner.routing_hospitals.every(h=>offer.hospital_ids.includes(h)));
  const audit=(await coord.request('/audit?gap_id='+encodeURIComponent(offer.gap_id))).items;
  for(const action of ['Proposed offer','Approved offer','Sent offer','Accepted offer'])check('Audit '+action,audit.some(a=>a.action===action));
  await physician.page.getByRole('link',{name:'My shift',exact:true}).click();
  await physician.page.getByText('On shift',{exact:true}).waitFor();
  step='final browser evidence';
  await coord.page.getByRole('link',{name:'Schedule',exact:true}).click();
  await coord.page.locator('.roster-row').filter({hasText:'Dr. Grace Okafor'}).click();
  await coord.page.screenshot({path:path.join(output,'schedule-desktop.png'),fullPage:true});
  await coord.page.setViewportSize({width:390,height:844});
  await coord.page.screenshot({path:path.join(output,'schedule-mobile.png')});
  check('Reference manifest unchanged',(await coord.request('/admin/references')).manifest.fingerprint===refs.manifest.fingerprint);
  check('No browser page errors',pageErrors.length===0,pageErrors);
  await fs.writeFile(path.join(output,'evidence.json'),JSON.stringify({checks,failures,offer,arrived,audit,pageErrors},null,2));
  console.log(JSON.stringify({output,checks,failures,pageErrors},null,2));
  assert.deepEqual(failures,[]);
 }catch(e){
  console.error('E2E step: '+step);if(coord)await coord.page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{});
  console.error(JSON.stringify({output,checks,failures,pageErrors},null,2));throw e;
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
